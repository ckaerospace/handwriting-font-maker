import fs from "fs";
import { loadImage } from "./load.mjs";
import { Classifier } from "../../public/js/classifier.js";
import { preparePhoto, labelWithTranscript, chooseBest, missingChars, buildModel, measureSpace } from "../../public/js/pipeline.js";
import { buildTTF, buildOTF, buildWOFF } from "../../public/js/font.js";
import * as opentype from "../../public/vendor/opentype.min.mjs";
const meta = JSON.parse(fs.readFileSync("public/model/cls.json"));
const buf = fs.readFileSync("public/model/cls.f16");
const cls = new Classifier(meta, buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const [,, page, outBase, name = "My Handwriting"] = process.argv;
const gt = JSON.parse(fs.readFileSync(page + ".json"));
const im = loadImage(page + ".jpg");
let t = Date.now();
const prep = preparePhoto(im.data, im.w, im.h);
const lab = labelWithTranscript(prep, gt.transcript, meta, cls);
console.log("analyse ms", Date.now() - t, "samples", lab.samples.length);
const best = chooseBest(lab.samples, meta);
console.log("chars", best.size, "missing", missingChars(best).join(""));
const cuts = lab.samples.filter(s => s.cutL || s.cutR).length / lab.samples.length;
const params = { name, sideBearing: 45, tracking: 0, spaceWidth: measureSpace([prep]), smooth: 0.6, thickness: 0, joinCursive: cuts > 0.3 };
t = Date.now();
const model = buildModel(best, params);
const ttf = buildTTF(model, { name });
console.log("model+ttf ms", Date.now() - t, "glyphs", model.glyphs.length, "ttf bytes", ttf.length, "cut frac", cuts.toFixed(2));
fs.writeFileSync(outBase + ".ttf", ttf);
const otf = buildOTF(model, { name }, opentype); fs.writeFileSync(outBase + ".otf", Buffer.from(otf));
const woff = await buildWOFF(ttf); fs.writeFileSync(outBase + ".woff", woff);
console.log("otf", otf.byteLength, "woff", woff.length);
const lowc = [...lab.samples].filter(s => s.p !== null && s.p < 0.25).length;
console.log("low-confidence glyphs", lowc, "of", lab.samples.length);
